/**
 * Utility function.
 * Given an object, returns the keys which have value true.
 * @param {Object} obj Object to get the keys from (as strings)
 */
function keysWithTruthyValue(obj) {
  return Object.keys(obj).reduce(
    (trueKeys, key) => (obj[key] ? [...trueKeys, key] : trueKeys),
    [] // initial value of trueKeys
  );
}

